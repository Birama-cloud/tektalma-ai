_FONT_CANDIDATES = [  # polices avec les lettres wolof (ë, ñ, ŋ, à, ó)
    ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
    ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/segoeuib.ttf"),
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    ("/Library/Fonts/Arial.ttf", "/Library/Fonts/Arial Bold.ttf"),
]


def _fonts():
    from pathlib import Path

    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    if "TK" in pdfmetrics.getRegisteredFontNames():
        return "TK", "TK-Bold"
    for regular, bold in _FONT_CANDIDATES:
        if Path(regular).exists() and Path(bold).exists():
            pdfmetrics.registerFont(TTFont("TK", regular))
            pdfmetrics.registerFont(TTFont("TK-Bold", bold))
            return "TK", "TK-Bold"
    return "Helvetica", "Helvetica-Bold"


def checklist_pdf(fiche: dict, sources: list, lang: str) -> bytes:
    """Fiche PDF A4 au format document officiel (bande drapeau, cases à cocher, sources)."""
    import io

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    L = LABELS.get(lang, LABELS["fr"])
    regular, bold = _fonts()
    ink, muted, green = colors.HexColor("#1B2235"), colors.HexColor("#4A5470"), colors.HexColor("#00853F")
    e = html.escape

    st = {
        "brand": ParagraphStyle("brand", fontName=bold, fontSize=9, textColor=green, spaceAfter=4),
        "title": ParagraphStyle("title", fontName=bold, fontSize=20, leading=24, textColor=ink, spaceAfter=6),
        "resume": ParagraphStyle("resume", fontName=regular, fontSize=10.5, leading=15, textColor=muted, spaceAfter=10),
        "h2": ParagraphStyle("h2", fontName=bold, fontSize=12, textColor=green, spaceBefore=12, spaceAfter=6),
        "item": ParagraphStyle("item", fontName=regular, fontSize=10.5, leading=15, textColor=ink,
                               leftIndent=16, bulletIndent=0, spaceAfter=4,
                               bulletFontName=regular, bulletFontSize=11),
        "fact_label": ParagraphStyle("fl", fontName=regular, fontSize=8.5, textColor=muted),
        "fact_value": ParagraphStyle("fv", fontName=bold, fontSize=11, leading=14, textColor=ink),
        "src": ParagraphStyle("src", fontName=regular, fontSize=8.5, leading=12, textColor=muted, spaceAfter=5),
        "foot": ParagraphStyle("foot", fontName=regular, fontSize=8, leading=11, textColor=muted, spaceBefore=14),
    }

    story = [Paragraph("TEKTALMA AI", st["brand"]),
             Paragraph(e(fiche.get("titre", "")), st["title"])]
    if fiche.get("resume"):
        story.append(Paragraph(e(fiche["resume"]), st["resume"]))

    facts = [[Paragraph(L[k], st["fact_label"]), Paragraph(e(fiche[k]), st["fact_value"])]
             for k in ("cout", "delai") if fiche.get(k)]
    if facts:
        cells = [[Table([[f[0]], [f[1]]], colWidths=[78 * mm]) for f in facts]]
        box = Table(cells, colWidths=[82 * mm] * len(facts), hAlign="LEFT")
        box.setStyle(TableStyle([("BOX", (i, 0), (i, 0), 1.2, ink) for i in range(len(facts))]
                                + [("VALIGN", (0, 0), (-1, -1), "TOP"),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 6)]))
        story += [box, Spacer(1, 4)]

    def section(key, numbered=False):
        items = fiche.get(key) or []
        if not items:
            return
        story.append(Paragraph(L[key], st["h2"]))
        for n, item in enumerate(items, start=1):
            bullet = f"{n}." if numbered else "\u25a1"
            story.append(Paragraph(e(item), st["item"], bulletText=bullet))

    section("documents")
    section("etapes", numbered=True)
    section("lieux")
    section("conseils")

    if sources:
        story.append(Paragraph(L["sources"], st["h2"]))
        for s in sources:
            story.append(Paragraph(
                f"{e(s['title'])} — {e(s['organisme'])}<br/>"
                f"<link href='{e(s['url'])}' color='#00853F'>{e(s['url'])}</link>", st["src"]))
    story.append(Paragraph(f"{L['made']} {date.today().strftime('%d/%m/%Y')}. {L['warn']}", st["foot"]))

    def page_deco(canvas, doc):  # bande aux couleurs du drapeau
        w, h = A4
        for i, c in enumerate(("#00853F", "#FDEF42", "#E31B23")):
            canvas.setFillColor(colors.HexColor(c))
            canvas.rect(i * w / 3, h - 7 * mm, w / 3 + 1, 7 * mm, stroke=0, fill=1)

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                      topMargin=18 * mm, bottomMargin=16 * mm,
                      title=fiche.get("titre", "TEKTALMA AI"), author="TEKTALMA AI").build(
        story, onFirstPage=page_deco, onLaterPages=page_deco)
    return buf.getvalue()
