LIST_KEYS = ("documents", "etapes", "lieux", "conseils")


def generate_checklist(llm, docs, question_fr: str, lang: str) -> dict:
    fiche = _checklist(llm, docs, question_fr, "fr" if lang == "wo" else lang)
    return fiche_to_wolof(llm, fiche) if lang == "wo" else fiche


def _checklist(llm, docs, question_fr: str, lang: str) -> dict:
    context = build_context(docs)
    raw = llm.generate(f"SOURCES :\n{context}\n\nDEMANDE : {question_fr}",
                       system=SYSTEM.format(lang=LANG_NAMES.get(lang, "français")), json_mode=True)
    data = parse_json(raw)
    allowed = allowed_numbers(context)
    def ok(x):  # garde-fous : chiffre sourcé + une seule langue
        return bool(x) and is_supported(str(x), allowed) and not looks_wolof(str(x))

    fiche = {"titre": str(data.get("titre") or ""), "resume": str(data.get("resume") or "")}
    if not ok(fiche["resume"]):
        fiche["resume"] = ""
    for key in LIST_KEYS:
        fiche[key] = [str(x) for x in (data.get(key) or []) if ok(x)][:7]
    for key in ("cout", "delai"):
        value = data.get(key)
        fiche[key] = str(value) if ok(value) else None
    return fiche


